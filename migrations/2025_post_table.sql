-- Post Table

CREATE TABLE Post (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board VARCHAR DEFAULT NULL REFERENCES Board(url) ON DELETE CASCADE,
    thread_id BIGINT DEFAULT NULL REFERENCES Post(id) ON DELETE CASCADE,

    subject VARCHAR DEFAULT NULL,
    comment TEXT NOT NULL,
    user_id BIGINT NOT NULL,
    user_trip BIGINT DEFAULT NULL,
    user_country CHAR(2) NOT NULL DEFAULT 'ZZ',
    user_name VARCHAR NOT NULL DEFAULT 'বানন',

    birth_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    change_time TIMESTAMP WITH TIME ZONE DEFAULT NULL,
    bump_time TIMESTAMP WITH TIME ZONE DEFAULT NULL,

    reply_count INT DEFAULT NULL,
    is_redacted BOOLEAN NOT NULL DEFAULT FALSE,
    is_saged BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT chk_post_type_integrity
        CHECK (
    	    (
	        thread_id IS NULL
		AND board IS NOT NULL AND TRIM(board) != ''
		AND subject IS NOT NULL AND TRIM(subject) != ''
		AND comment IS NOT NULL AND TRIM(comment) != ''
		AND change_time IS NOT NULL AND bump_time IS NOT NULL
		AND reply_count IS NOT NULL AND reply_count >= 0
	    )
	    OR
	    (
		thread_id IS NOT NULL
		AND board IS NULL
		AND subject IS NULL
		AND comment IS NOT NULL AND TRIM(comment) != ''
		AND change_time IS NULL AND bump_time IS NULL
		AND reply_count IS NULL
		AND is_saged IS FALSE
	    )
    	)
);


-- Partial Indexes

CREATE INDEX idx_board_threads
ON Post (board, bump_time DESC)
WHERE thread_id IS NULL AND is_redacted IS FALSE;

CREATE INDEX idx_thread_replies
ON Post (thread_id, id ASC)
WHERE thread_id IS NOT NULL;
